#!/usr/bin/env node
// The NbE core written in heff (compiler/) against the PureScript
// reference: for every definition of the corpus (test/nbe/*.hf),
// `heff dump-nbe` gives the definition over compiler/syntax.hf's formers
// and the normal forms the reference computes; a generated heff program
// rebuilds the globals with compiler/top.hf, normalizes with
// compiler/{eval,readback}.hf, prints with compiler/print.hf, and its
// watches hold the two sides to the same text.
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const heff = (...args) => spawnSync("node", [join(root, "bin", "reference.mjs"), ...args], { cwd: root, encoding: "utf8" });

let failed = 0, defs = 0;
const corpus = readdirSync(join(root, "test", "nbe")).filter((f) => f.endsWith(".hf"));
const lines = [
  "-- Generated by test/nbe-port.mjs: the corpus' definitions, rebuilt and",
  "-- normalized by compiler/, held to the reference's normal forms.",
  "",
  "import array as A",
  "import compiler.dict as D",
  "import compiler.eval as E",
  "import compiler.params as P",
  "import compiler.print as Pr",
  "import compiler.syntax as Sx",
  "import compiler.top as T",
  "import map as M",
  "import prelude",
  "",
  "g0 : E.Globals",
  "g0 = T.emptyGlobals",
  "",
];
let n = 0;
for (const f of corpus) {
  const r = heff("dump-nbe", join("test", "nbe", f));
  if (r.status !== 0) { failed++; console.log(`FAIL dump-nbe ${f}:\n${r.stderr}`); continue; }
  const blocks = r.stdout.split("=def ").slice(1);
  for (const b of blocks) {
    const field = (name) => {
      const m = b.match(new RegExp(`^=${name} (.*)$`, "m"));
      return m ? m[1] : null;
    };
    const [key, kind] = b.split("\n")[0].split(" ");
    const ty = field("ty"), body = field("body"), normTy = field("normTy"), normEl = field("normEl");
    if (!ty || !body || !normTy || !normEl) { failed++; console.log(`FAIL dump of ${key}: missing fields`); continue; }
    defs++;
    lines.push(
      `ty${n} : Sx.Ty`,
      `ty${n} = ${ty}`,
      ``,
      `d${n} : Sx.Tm`,
      `d${n} = ${body}`,
      ``,
      `-- >>> Pr.showTy (T.normTy g${n} ty${n})`,
      `-- ${JSON.stringify(normTy)}`,
      ``,
      `-- >>> Pr.showEl (T.normEl g${n} ${JSON.stringify(key)} ty${n} d${n})`,
      `-- ${JSON.stringify(normEl)}`,
      ``,
      `g${n + 1} : E.Globals`,
      `g${n + 1} = ${kind === "prim" ? `T.definePrim g${n} ${JSON.stringify(key)} ty${n}` : `T.define g${n} ${JSON.stringify(key)} ty${n} d${n}`}`,
      ``
    );
    n++;
  }
}

mkdirSync(join(root, "ref"), { recursive: true });
const gen = join(root, "ref", "nbe-port-gen.hf");
writeFileSync(gen, lines.join("\n"));
const t = heff("test", gen);
process.stdout.write(t.stdout.split("\n").filter((l) => l.startsWith("FAIL")).join("\n"));
const ok = t.status === 0 && failed === 0;
console.log(`nbe port: ${defs} definitions${ok ? "" : " (with failures)"}${t.status === 0 ? "" : `\n${t.stdout.split("\n").slice(-2).join("\n")}`}`);
rmSync(gen, { force: true });
process.exit(ok ? 0 : 1);
