#!/usr/bin/env node
// The compiler written in heff (compiler/) against the PureScript
// reference, end to end: for every file of the corpus (test/nbe/*.hf),
// the reference elaborates it (`heff dump-nbe`), the port reads the same
// SOURCE TEXT through its own lexer, reader and elaborator
// (compiler/toplevel.hf checkSource), and a generated program's watches
// hold each definition's type and body to the same printed core.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const heff = (...args) => spawnSync("node", [join(root, "bin", "heff.mjs"), ...args], { cwd: root, encoding: "utf8" });

let failed = 0, defs = 0;
const corpus = readdirSync(join(root, "test", "nbe")).filter((f) => f.endsWith(".hf"));
const lines = [
  "-- Generated by test/selfhost-port.mjs: the corpus' sources, elaborated",
  "-- whole by compiler/, each definition held to the reference's core.",
  "",
  "import compiler.toplevel as T",
  "import prelude",
  "",
];
let n = 0;
for (const f of corpus) {
  const mod = "test.nbe." + f.replace(".hf", "");
  const src = readFileSync(join(root, "test", "nbe", f), "utf8");
  const r = heff("dump-nbe", join("test", "nbe", f));
  if (r.status !== 0) { failed++; console.log(`FAIL dump-nbe ${f}:\n${r.stderr}`); continue; }
  lines.push(`src${n} : String`, `src${n} = ${JSON.stringify(src)}`, ``, `top${n} : T.TopResult`, `top${n} = T.checkSource ${JSON.stringify(mod)} src${n}`, ``);
  for (const b of r.stdout.split("=def ").slice(1)) {
    const key = b.split("\n")[0].split(" ")[0];
    const field = (name) => {
      const m = b.match(new RegExp(`^=${name} (.*)$`, "m"));
      return m ? m[1] : null;
    };
    defs++;
    lines.push(
      `-- >>> T.tyDump top${n} ${JSON.stringify(key)}`,
      `-- ${JSON.stringify(field("ty"))}`,
      ``,
      `-- >>> T.bodyDump top${n} ${JSON.stringify(key)}`,
      `-- ${JSON.stringify(field("body"))}`,
      ``
    );
  }
  n++;
}

mkdirSync(join(root, "ref"), { recursive: true });
const gen = join(root, "ref", "selfhost-port-gen.hf");
writeFileSync(gen, lines.join("\n"));
const t = heff("test", gen);
process.stdout.write(t.stdout.split("\n").filter((l) => l.startsWith("FAIL") || l.startsWith("  ")).slice(0, 40).join("\n") + "\n");
const ok = t.status === 0 && failed === 0;
console.log(`selfhost: ${defs} definitions elaborated alike${ok ? "" : " (with failures)"}`);
if (ok) rmSync(gen, { force: true });
process.exit(ok ? 0 : 1);
